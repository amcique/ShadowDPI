std::vector<std::byte> make_fake_client_hello(std::string_view domain)
{
    constexpr std::size_t sni_header_size = 9;
    const std::size_t part0_size = kClientHelloPart0.size();
    const std::size_t part1_size = kClientHelloPart1.size();
    const std::size_t name_size = domain.size();
    const std::size_t packet_size =
        part0_size + part1_size + sni_header_size + name_size;

    std::vector<std::byte> packet(packet_size);
    std::memcpy(packet.data(), kClientHelloPart0.data(), part0_size);
    std::memcpy(packet.data() + part0_size + sni_header_size + name_size,
                kClientHelloPart1.data(), part1_size);

    std::uniform_int_distribution<int> byte_distribution(0, 0xFF);
    for (auto& byte : packet) {
        if (byte == std::byte{0xAA}) {
            byte = static_cast<std::byte>(byte_distribution(random_engine()));
        }
    }

    write_be16(packet.data() + 0x0003,
               static_cast<std::uint16_t>(packet_size - 5));
    write_be16(packet.data() + 0x0007,
               static_cast<std::uint16_t>(packet_size - 9));
    write_be16(packet.data() + 0x0072,
               static_cast<std::uint16_t>(packet_size - 116));

    write_be16(packet.data() + part0_size, 0x0000);
    write_be16(packet.data() + part0_size + 2,
               static_cast<std::uint16_t>(name_size + 5));
    write_be16(packet.data() + part0_size + 4,
               static_cast<std::uint16_t>(name_size + 3));
    packet[part0_size + 6] = std::byte{0x00};
    write_be16(packet.data() + part0_size + 7,
               static_cast<std::uint16_t>(name_size));
    std::memcpy(packet.data() + part0_size + sni_header_size,
                domain.data(), name_size);

    return packet;
}

std::vector<std::vector<std::byte>> make_random_fake_payloads(
    unsigned int count,
    unsigned int max_size)
{
    if (count == 0 || count > kMaxFakePackets || max_size < 9) {
        throw std::invalid_argument("invalid fake payload generator parameters");
    }

    // 8..(max_size-1) bytes.
    std::uniform_int_distribution<unsigned int> length_distribution(
        0, max_size - 9);
    std::uniform_int_distribution<unsigned int> byte_distribution(0, 0xFE);

    std::vector<std::vector<std::byte>> result;
    result.reserve(count);
    for (unsigned int index = 0; index < count; ++index) {
        const std::size_t length = 8 + length_distribution(random_engine());
        std::vector<std::byte> payload(length);
        for (auto& byte : payload) {
            byte = static_cast<std::byte>(byte_distribution(random_engine()));
        }
        result.push_back(std::move(payload));
    }
    return result;
}

